package com.ozonehis.cli;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.io.File;
import java.io.IOException;
import java.net.URISyntaxException;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

class EnvGenTest {

    private File composeRoot;
    private File distroDir;

    @BeforeEach
    void setUp() throws URISyntaxException {
        composeRoot = new File(getClass().getResource("/fixture/compose").toURI());
        distroDir = new File(getClass().getResource("/fixture/distro").toURI());
    }

    private Map<String, String> generate(boolean ssoEnabled) throws IOException {
        return generate(Model.load(new File(composeRoot, "model.yml")), ssoEnabled);
    }

    private Map<String, String> generate(Model model, boolean ssoEnabled) throws IOException {
        return generate(model, ssoEnabled, Selection.load(new File(distroDir, "ozone.yml")));
    }

    private Map<String, String> generate(Model model, boolean ssoEnabled, Selection selection) throws IOException {
        Map<String, String> runtime = new LinkedHashMap<String, String>();
        runtime.put("HOST_NAME", "demo.example.org");
        runtime.put("SERVER_SCHEME", "https");
        runtime.put("ENABLE_SSO", Boolean.toString(ssoEnabled));
        runtime.put("DB_INIT_LIST", "alpha beta");
        // The vars owners come from the resolved plan, exactly like the CLI.
        Plan plan = new Resolver(model, selection, composeRoot, distroDir).resolve();
        lastGen = new EnvGen(ssoEnabled, plan.owners);
        return lastGen.generate(
                new File(composeRoot, "vars.yml"),
                // The vars the deployment path reads: the resolved file, as
                // generated by 'ozone resolve' from the source vars.yml.
                new File(distroDir, "resolved/vars.yml"),
                model.deployment,
                runtime);
    }

    private Selection selection(String appsYaml, String addonsYaml) throws IOException {
        String yaml = "selection:\n  apps:\n" + appsYaml + "\n  addons:\n"
                + addonsYaml.replaceAll("(?m)^", "  ") + "\n";
        File file = File.createTempFile("ozone", ".yml");
        java.nio.file.Files.write(file.toPath(), yaml.getBytes(java.nio.charset.StandardCharsets.UTF_8));
        file.deleteOnExit();
        return Selection.load(file);
    }

    private EnvGen lastGen;

    @Test
    void mergesOverlayDeploymentVars() throws IOException {
        Model model = Model.load(new File(composeRoot, "model.yml"));
        model.mergeOverlay(Yamls.load(new File(distroDir, "resolved/model-overrides.yml")));
        Map<String, String> env = generate(model, true);
        assertEquals("${HOST_NAME}:9090", env.get("C2C_HOSTNAME")); // new service knob
        assertEquals("c2c", env.get("C2C_EXTRA")); // new extra global
    }

    @Test
    void keepsVarReferencesRawForDeploymentTimeOverrides() throws IOException {
        // The .env keeps ${HOST_NAME} references raw: compose resolves them
        // at runtime, so a deployment can override HOST_NAME without
        // regenerating.
        Map<String, String> env = generate(true);
        assertEquals("${HOST_NAME}:8080", env.get("ALPHA_HOSTNAME"));
        assertEquals("demo.example.org", env.get("HOST_NAME")); // the runtime value
    }

    @Test
    void substituteResolvesChainedReferencesForDisplay() throws IOException {
        Map<String, String> resolved = EnvGen.substitute(generate(true));
        assertEquals("demo.example.org:8080", resolved.get("ALPHA_HOSTNAME"));
    }

    @Test
    void mergesCodeDistroAndDeploymentVarsWithTheRightPrecedence() throws IOException {
        Map<String, String> env = generate(true);
        assertEquals("alphauser", env.get("ALPHA_USER"));   // code vars
        assertEquals("alphadb", env.get("ALPHA_DB"));
        assertEquals("UTC", env.get("TIMEZONE"));            // deployment extra
    }

    @Test
    void mergesSsoBlocksOnlyWhenSsoIsEnabled() throws IOException {
        assertTrue(generate(true).containsKey("ALPHA_CLIENT_SECRET"));
        assertFalse(generate(false).containsKey("ALPHA_CLIENT_SECRET"));
    }

    @Test
    void runtimeRootsAreWrittenFirstSoReferencesResolveInFileOrder() throws IOException {
        // Compose interpolates env-file values in file order, single pass:
        // HOST_NAME must precede the values that reference it.
        List<String> lines = EnvGen.toFileLines(generate(true));
        int hostNameIndex = lines.indexOf("HOST_NAME=demo.example.org");
        int alphaHostnameIndex = lines.indexOf("ALPHA_HOSTNAME=${HOST_NAME}:8080");
        assertTrue(hostNameIndex >= 0 && alphaHostnameIndex >= 0, lines.toString());
        assertTrue(hostNameIndex < alphaHostnameIndex, lines.toString());
    }

    @Test
    void runtimeValuesWin() throws IOException {
        assertEquals("alpha beta", generate(true).get("DB_INIT_LIST"));
        assertEquals("true", generate(true).get("ENABLE_SSO"));
    }

    @Test
    void doesNotFlattenNamedBlocksCollidingWithSubBlockNames() throws IOException {
        // The named block apps.keycloak carries the Keycloak common values; its
        // own keys must never leak into the .env as flattened 'common'/'paths'
        // values.
        Map<String, String> env = generate(true);
        assertFalse(env.containsKey("common"));
        assertFalse(env.containsKey("paths"));
        assertEquals("kcadmin", env.get("KEYCLOAK_USER")); // merged as a named block
    }

    @Test
    void unselectedOwnersAreFilteredOutOfTheEnv() throws IOException {
        // The fixture selection is alpha + beta + keycloak (integration
        // alpha-beta activates; addon 'extra' is not enabled).
        Map<String, String> env = generate(true);
        assertTrue(env.containsKey("ALPHA_USER"), env.toString());  // selected app
        assertTrue(env.containsKey("BETA_VAR"), env.toString());
        assertTrue(env.containsKey("EIP_VAR"), env.toString());     // activated integration
        assertFalse(env.containsKey("GAMMA_VAR"), env.toString());  // unselected app
        assertFalse(env.containsKey("ADDON_VAR"), env.toString());  // disabled addon
        // Infrastructure sections are always merged.
        assertTrue(env.containsKey("MYSQL_MAX_CONNECTIONS"), env.toString());
        assertTrue(env.containsKey("BACKUP_VAR"), env.toString());
        assertTrue(env.containsKey("RESTIC_REPOSITORY"), env.toString());
        assertTrue(env.containsKey("MYSQL_ROOT_PASSWORD"), env.toString());
    }

    @Test
    void varsFromPullsTheNamedBlocksIntoTheEnv() throws IOException {
        // delta is selected alone; its vars.yml block declares vars-from apps.gamma.
        Map<String, String> env = generate(
                Model.load(new File(composeRoot, "model.yml")), false, selection("  - delta", ""));
        assertTrue(env.containsKey("DELTA_VAR"), env.toString());
        assertTrue(env.containsKey("GAMMA_VAR"), env.toString());
        assertFalse(env.containsKey("ALPHA_USER"), env.toString());
    }

    @Test
    void varsFromEdgesDeclaredInTheDistroVarsFileAreFollowedToo() throws IOException {
        // A child distro may add its own vars-from edge via its vars overrides;
        // the resolved vars file carries it and the closure follows it.
        File distroVars = File.createTempFile("vars", ".yml");
        java.nio.file.Files.write(distroVars.toPath(),
                "apps:\n  delta:\n    vars-from: [apps.beta]\n"
                        .getBytes(java.nio.charset.StandardCharsets.UTF_8));
        Selection sel = selection("  - delta", "");
        Model model = Model.load(new File(composeRoot, "model.yml"));
        Plan plan = new Resolver(model, sel, composeRoot, distroDir).resolve();
        EnvGen gen = new EnvGen(false, plan.owners);
        Map<String, String> env = gen.generate(new File(composeRoot, "vars.yml"), distroVars,
                model.deployment, new LinkedHashMap<String, String>());
        assertTrue(env.containsKey("DELTA_VAR"), env.toString());
        assertTrue(env.containsKey("GAMMA_VAR"), env.toString()); // code-level edge
        assertTrue(env.containsKey("BETA_VAR"), env.toString());  // distro-level edge
    }

    @Test
    void rejectsVarsFromCycles() throws IOException {
        File vars = File.createTempFile("vars", ".yml");
        java.nio.file.Files.write(vars.toPath(),
                ("apps:\n  a:\n    common:\n      A_VAR: a\n    vars-from: [apps.b]\n"
                        + "  b:\n    common:\n      B_VAR: b\n    vars-from: [apps.a]\n")
                        .getBytes(java.nio.charset.StandardCharsets.UTF_8));
        EnvGen gen = new EnvGen(false, java.util.Collections.singleton("apps.a"));
        IOException e = org.junit.jupiter.api.Assertions.assertThrows(IOException.class, () ->
                gen.generate(vars, new File(distroDir, "resolved/vars.yml"),
                        Model.load(new File(composeRoot, "model.yml")).deployment,
                        new LinkedHashMap<String, String>()));
        assertTrue(e.getMessage().contains("cycle"), e.getMessage());
        assertTrue(e.getMessage().contains("apps.a"), e.getMessage());
    }

    @Test
    void rejectsVarsFromTargetsWithNoBlock() throws IOException {
        File vars = File.createTempFile("vars", ".yml");
        java.nio.file.Files.write(vars.toPath(),
                "apps:\n  a:\n    common:\n      A_VAR: a\n    vars-from: [apps.nope]\n"
                        .getBytes(java.nio.charset.StandardCharsets.UTF_8));
        EnvGen gen = new EnvGen(false, java.util.Collections.singleton("apps.a"));
        IOException e = org.junit.jupiter.api.Assertions.assertThrows(IOException.class, () ->
                gen.generate(vars, new File(distroDir, "resolved/vars.yml"),
                        Model.load(new File(composeRoot, "model.yml")).deployment,
                        new LinkedHashMap<String, String>()));
        assertTrue(e.getMessage().contains("apps.nope"), e.getMessage());
        assertTrue(e.getMessage().contains("no block"), e.getMessage());
    }

    @Test
    void distroRelativePathsStayAsDistroPathReferences() throws IOException {
        // The .env must be portable: paths are emitted as ${DISTRO_PATH}/...
        // references (DISTRO_PATH is a runtime root at the top of the file),
        // so a deployment overrides one line and everything follows.
        Map<String, String> env = generate(true);
        assertEquals("${DISTRO_PATH}/data", env.get("SQL_SCRIPTS_PATH"));
        assertEquals("${DISTRO_PATH}/data", env.get("ALPHA_DATA_PATH"));
        // The invocation provides DISTRO_PATH (command prefix / runner export):
        Map<String, String> provided = new LinkedHashMap<String, String>(env);
        provided.put("DISTRO_PATH", distroDir.getAbsolutePath());
        assertEquals(new File(distroDir, "data").getPath(), EnvGen.substitute(provided).get("SQL_SCRIPTS_PATH"));
    }
}
